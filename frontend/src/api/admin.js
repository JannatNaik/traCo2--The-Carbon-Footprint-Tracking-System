import client from './client';
export const adminLogin = (data) => client.post('/api/admin/auth/login', data);
export const getAdminDashboard = () => client.get('/api/admin/dashboard');
export const getUsers = () => client.get('/api/admin/users');
export const updateUserStatus = (id, is_active) => client.patch(`/api/admin/users/${id}/status`, { is_active });
export const getAdminDevices = () => client.get('/api/admin/devices');
export const updateDevice = (id, data) => client.patch(`/api/admin/devices/${id}`, data);
export const getSensorData = (page) => client.get('/api/admin/sensor-data', { params: { page } });
export const getCarbonFactors = () => client.get('/api/admin/carbon-factors');
export const createCarbonFactor = (data) => client.post('/api/admin/carbon-factors', data);
export const updateCarbonFactor = (id, data) => client.put(`/api/admin/carbon-factors/${id}`, data);
export const deleteCarbonFactor = (id) => client.delete(`/api/admin/carbon-factors/${id}`);
export const getAdminBadges = () => client.get('/api/admin/rewards/badges');
export const createBadge = (data) => client.post('/api/admin/rewards/badges', data);
export const updateBadge = (id, data) => client.put(`/api/admin/rewards/badges/${id}`, data);
export const deleteBadge = (id) => client.delete(`/api/admin/rewards/badges/${id}`);
export const getAdminChallenges = () => client.get('/api/admin/rewards/challenges');
